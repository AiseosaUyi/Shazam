const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');
const cp = require('child_process');
const load = (p) => require(path.join(process.cwd(), p));
const read = (p) => fs.readFileSync(path.join(process.cwd(), p), 'utf8');
const taskDir = __dirname;
const os = require('os');
const { chunk, unique } = load('arrays.js');
assert.deepEqual(unique([3, 1, 3, 2, 1]), [3, 1, 2]);
assert.deepEqual(unique(['a', 'a']), ['a']);
assert.deepEqual(unique([1, '1']), [1, '1']);
assert.deepEqual(chunk([1, 2, 3], 2), [[1, 2], [3]]);
const input = [1, 1];
unique(input);
assert.deepEqual(input, [1, 1], 'must not mutate input');
const testSrc = read('arrays.test.js');
assert.ok(/chunk/.test(testSrc), 'existing chunk test must be kept');
assert.ok((testSrc.match(/unique/g) || []).length >= 2, 'need unique tests');
let r = cp.spawnSync(process.execPath, ['--test', 'arrays.test.js'], { cwd: process.cwd(), encoding: 'utf8' });
assert.equal(r.status, 0, r.stdout.slice(-600));
const d = fs.mkdtempSync(path.join(os.tmpdir(), 'eval-mut-'));
fs.writeFileSync(path.join(d, 'arrays.js'), read('arrays.js').replace(/function unique\(arr\) \{[\s\S]*?\n\}/, 'function unique(arr) { return arr.slice(); }'));
fs.copyFileSync('arrays.test.js', path.join(d, 'arrays.test.js'));
r = cp.spawnSync(process.execPath, ['--test', 'arrays.test.js'], { cwd: d, encoding: 'utf8' });
fs.rmSync(d, { recursive: true, force: true });
assert.notEqual(r.status, 0, 'tests must fail against a broken unique');
