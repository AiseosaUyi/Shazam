// Bundles the desktop bridge (cli/bridge.js + desktop/bridge-core.js) into one dependency-free
// file served at /arcwork-bridge.js, so anyone can connect their computer with plain Node:
//   curl -fsSL https://arcwork-ai.vercel.app/arcwork-bridge.js -o ~/.arcwork-bridge.js
//   node ~/.arcwork-bridge.js connect
// and the `arcwork` npm package (packages/arcwork) for: npx arcwork connect
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const core = readFileSync('desktop/bridge-core.js', 'utf8');
let cli = readFileSync('cli/bridge.js', 'utf8').replace(/^#!.*\n/, '');
if (!cli.includes("require('../desktop/bridge-core')")) throw new Error('gen-bridge: bridge-core import not found');
cli = cli.replace("require('../desktop/bridge-core')", '__core');

const bundle = (command) => `#!/usr/bin/env node
// Arcwork bridge: lets Arcwork's agents work in folders you allow on this computer.
// Generated by scripts/gen-bridge.mjs. Needs only Node 18+. Source: github.com/AiseosaUyi/Shazam
'use strict';
const __core = (function () {
  const module = { exports: {} };
  const exports = module.exports;
${core}
  return module.exports;
})();
${cli.replace(/shazam-bridge/g, command)}`;

mkdirSync('public', { recursive: true });
writeFileSync('public/arcwork-bridge.js', bundle('node ~/.arcwork-bridge.js'));
// The `arcwork` npm package, so terminal users can run: npx arcwork connect
mkdirSync('packages/arcwork/bin', { recursive: true });
writeFileSync('packages/arcwork/bin/arcwork.js', bundle('npx arcwork'), { mode: 0o755 });
console.log('gen-bridge: wrote public/arcwork-bridge.js and packages/arcwork/bin/arcwork.js');
