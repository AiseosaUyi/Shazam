// Embeds migrations/*.sql into a TS module so serverless bundles don't depend on
// file tracing to find them at runtime. Runs automatically before `next build`.
import fs from 'node:fs';
import path from 'node:path';

const dir = path.join(process.cwd(), 'migrations');
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
const entries = files.map((f) => `  { name: ${JSON.stringify(f)}, sql: ${JSON.stringify(fs.readFileSync(path.join(dir, f), 'utf8'))} },`);
const out = `// AUTO-GENERATED by scripts/gen-migrations.mjs — do not edit.\nexport const MIGRATIONS: Array<{ name: string; sql: string }> = [\n${entries.join('\n')}\n];\n`;
fs.writeFileSync(path.join(process.cwd(), 'src/lib/db/migrations.generated.ts'), out);
console.log(`Embedded ${files.length} migrations.`);
